"""
Generate supabase/seed.sql from the app's own data files
(web/src/data/zones.json and resources.json), so the database and the app always match.
Usage:  python scripts/make_seed.py
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
zones = json.load(open(os.path.join(ROOT, "web/src/data/zones.json"), encoding="utf-8"))
resources = json.load(open(os.path.join(ROOT, "web/src/data/resources.json"), encoding="utf-8"))


def hex_polygon(lat, lng, radius_km=25):
    """Same hexagon as web/src/lib/geo.ts -> hexPolygon()."""
    d_lat = radius_km / 111
    d_lng = radius_km / (111 * math.cos(math.radians(lat)))
    pts = []
    for i in range(6):
        a = math.radians(60 * i + 30)
        pts.append((round(lng + d_lng * math.cos(a), 6), round(lat + d_lat * math.sin(a), 6)))
    pts.append(pts[0])
    return "POLYGON((" + ", ".join(f"{x} {y}" for x, y in pts) + "))"


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def nearest_zone(lat, lng):
    best, bd = None, 1e9
    for z in zones:
        d = (z["lat"] - lat) ** 2 + ((z["lng"] - lng) * math.cos(math.radians(lat))) ** 2
        if d < bd:
            best, bd = z["id"], d
    return best


out = ["-- ResQGrid seed data for India (generated by scripts/make_seed.py). Run after schema.sql.", ""]
out.append("insert into public.zones (id, name, state, river, dist_river_km, slope_deg, flood_prone, relief_m, population, centroid, boundary) values")
rows = []
for z in zones:
    rows.append(
        f"  ({q(z['id'])}, {q(z['name'])}, {q(z['state'])}, {q(z.get('river'))}, {z['distRiverKm']}, {z['slopeDeg']}, "
        f"{'true' if z['floodProne'] else 'false'}, {z['reliefM']}, {z['population']}, "
        f"st_geogfromtext('SRID=4326;POINT({z['lng']} {z['lat']})'), st_geogfromtext('SRID=4326;{hex_polygon(z['lat'], z['lng'])}'))"
    )
out.append(",\n".join(rows))
out.append("on conflict (id) do update set name = excluded.name, state = excluded.state, river = excluded.river, dist_river_km = excluded.dist_river_km, "
           "slope_deg = excluded.slope_deg, flood_prone = excluded.flood_prone, relief_m = excluded.relief_m, "
           "population = excluded.population, centroid = excluded.centroid, boundary = excluded.boundary;")
out.append("")
out.append("insert into public.resources (id, type, name, lat, lng, capacity, occupied, status, zone_id) values")
rows = [
    f"  ({q(r['id'])}, {q(r['type'])}, {q(r['name'])}, {r['lat']}, {r['lng']}, {r['capacity']}, {r['occupied']}, {q(r['status'])}, {q(nearest_zone(r['lat'], r['lng']))})"
    for r in resources
]
out.append(",\n".join(rows))
out.append("on conflict (id) do nothing;")
out.append("")
out.append("-- To make a user an authority after they sign up in Supabase Auth:")
out.append("-- update public.profiles set role = 'authority' where id = (select id from auth.users where email = 'officer@example.com');")
path = os.path.join(ROOT, "supabase/seed.sql")
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("Wrote", path)
